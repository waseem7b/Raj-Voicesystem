#!/usr/bin/env python3
"""Regenerate INDEX.md views from the YAMLs in each call-review subdir.

Usage:
    python voicsito/call-review/render.py                # render all four
    python voicsito/call-review/render.py --only checklist
"""
import argparse
from collections import defaultdict
from pathlib import Path

import yaml


def _load_all(directory: Path, prefix: str) -> list:
    out = []
    for p in sorted(directory.glob(f"{prefix}-*.yaml")):
        data = yaml.safe_load(p.read_text()) or {}
        data["_path"] = p
        out.append(data)
    return out


def render_checklist(directory: Path) -> None:
    items = _load_all(directory, "CL")
    by_cat: dict[str, list] = defaultdict(list)
    for item in items:
        by_cat[item.get("category", "uncategorized")].append(item)

    lines = ["# Checklist", "",
             "_Generated by `render.py` — do not hand-edit._",
             "",
             f"Total: {len(items)} items.",
             ""]
    for cat in sorted(by_cat.keys()):
        lines.append(f"## {cat}")
        lines.append("")
        lines.append("| ID | Severity | Status | Question |")
        lines.append("|---|---|---|---|")
        for item in sorted(by_cat[cat], key=lambda i: i.get("id", "")):
            q = (item.get("question") or "").split("\n")[0].strip()
            lines.append(
                f"| {item.get('id', '?')} "
                f"| {item.get('severity', '?')} "
                f"| {item.get('status', '?')} "
                f"| {q} |"
            )
        lines.append("")
    (directory / "INDEX.md").write_text("\n".join(lines))


def render_changes(directory: Path) -> None:
    items = _load_all(directory, "CH")
    items.sort(key=lambda i: i.get("id", ""), reverse=True)  # newest first

    lines = ["# Changes", "",
             "_Generated by `render.py` — do not hand-edit._",
             "",
             f"Total: {len(items)} entries.",
             "",
             "| ID | When | Stage | Section | Hypothesis |",
             "|---|---|---|---|---|"]
    for it in items:
        hyp = (it.get("hypothesis") or "").split("\n")[0].strip()[:80]
        lines.append(
            f"| {it.get('id', '?')} "
            f"| {it.get('created', '?')} "
            f"| {it.get('stage', '?')} "
            f"| {it.get('section', '?')} "
            f"| {hyp} |"
        )
    (directory / "INDEX.md").write_text("\n".join(lines))


def render_observations(directory: Path) -> None:
    items = _load_all(directory, "OBS")
    items.sort(key=lambda i: i.get("id", ""), reverse=True)

    lines = ["# Observations", "",
             "_Generated by `render.py` — do not hand-edit._",
             "",
             f"Total: {len(items)} entries.",
             "",
             "| ID | When | Stage | Verdict | Fault | Confidence |",
             "|---|---|---|---|---|---|"]
    for it in items:
        lines.append(
            f"| {it.get('id', '?')} "
            f"| {it.get('created', '?')} "
            f"| {it.get('stage', '?')} "
            f"| {it.get('verdict', '?')} "
            f"| {it.get('fault_attribution', '?')} "
            f"| {it.get('confidence', '?')} |"
        )
    (directory / "INDEX.md").write_text("\n".join(lines))


def render_sessions(directory: Path) -> None:
    """Sessions are markdown files with YAML frontmatter; pull frontmatter only."""
    sessions = sorted(directory.glob("20*.md"), reverse=True)
    lines = ["# Sessions", "",
             "_Generated by `render.py` — do not hand-edit._",
             "",
             f"Total: {len(sessions)} sessions.",
             "",
             "| File | Mode | Calls reviewed | Findings | Changes |",
             "|---|---|---|---|---|"]
    for s in sessions:
        text = s.read_text()
        meta = {}
        if text.startswith("---"):
            end = text.find("\n---", 3)
            if end != -1:
                meta = yaml.safe_load(text[3:end]) or {}
        lines.append(
            f"| [{s.name}]({s.name}) "
            f"| {meta.get('mode', '?')} "
            f"| {len(meta.get('calls_reviewed') or [])} "
            f"| {len(meta.get('findings') or [])} "
            f"| {len(meta.get('changes') or [])} |"
        )
    (directory / "INDEX.md").write_text("\n".join(lines))


RENDERERS = {
    "checklist": render_checklist,
    "changes": render_changes,
    "observations": render_observations,
    "sessions": render_sessions,
}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--only", choices=sorted(RENDERERS.keys()),
                    help="render only one of the four directories")
    args = ap.parse_args()

    base = Path(__file__).resolve().parent
    targets = [args.only] if args.only else list(RENDERERS.keys())
    for name in targets:
        d = base / name
        if not d.exists():
            print(f"skip {name}: directory does not exist")
            continue
        RENDERERS[name](d)
        print(f"✓ rendered {name}/INDEX.md")
    return 0


if __name__ == "__main__":
    import sys
    sys.exit(main())
